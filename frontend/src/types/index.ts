/**
 * src/types/index.ts — Shared TypeScript types and constants
 *
 * This module defines the core data structures used throughout the RunForge frontend,
 * matching the backend entity model. All types are discriminated unions where applicable
 * for type-safe operations.
 */

/**
 * RunningLevel — Discriminated union type for member proficiency levels.
 * Must match the Java enum: BEGINNER | INTERMEDIATE | ADVANCED
 */
export type RunningLevel = 'BEGINNER' | 'INTERMEDIATE' | 'ADVANCED';

/**
 * Member — Represents a running group member.
 *
 * @property id - Unique identifier (auto-generated by backend)
 * @property firstName - Member's first name
 * @property lastName - Member's last name
 * @property email - Email address (unique)
 * @property phone - Phone number
 * @property level - Running proficiency level
 * @property joinedDate - ISO date string (YYYY-MM-DD) when member joined
 * @property active - Soft-delete flag; false means member is inactive
 */
export interface Member {
  id: number;
  firstName: string;
  lastName: string;
  email: string;
  phone: string;
  level: RunningLevel;
  joinedDate: string;
  active: boolean;
}

/**
 * RunningPlan — Represents a structured training program.
 *
 * @property id - Unique identifier
 * @property name - Plan name (e.g., "5km Beginner Plan")
 * @property description - Detailed plan description
 * @property level - Target running level
 * @property createdDate - ISO date string when plan was created
 */
export interface RunningPlan {
  id: number;
  name: string;
  description: string;
  level: RunningLevel;
  createdDate: string;
}

/**
 * PlanAssignment — Represents an assignment of a plan to a member.
 *
 * @property id - Unique identifier
 * @property member - Nested Member object
 * @property RunningPlan - Nested RunningPlan object
 * @property startDate - ISO date string when assignment starts
 * @property endDate - ISO date string when assignment ends
 * @property completed - Whether the member completed this plan
 */
export interface PlanAssignment {
  id: number;
  member: Member;
  RunningPlan: RunningPlan;
  startDate: string;
  endDate: string;
  completed: boolean;
}

/**
 * DashboardStats — Aggregated statistics for the dashboard.
 *
 * @property totalMembers - Total count of all member records
 * @property activeMembers - Count of members where active = true
 * @property totalPlans - Total count of training plans
 * @property activeAssignments - Count of assignments where completed = false
 * @property completedAssignments - Count of assignments where completed = true
 * @property membersByLevel - Distribution of active members by level
 */
export interface DashboardStats {
  totalMembers: number;
  activeMembers: number;
  totalPlans: number;
  activeAssignments: number;
  completedAssignments: number;
  membersByLevel: Record<RunningLevel, number>;
}

