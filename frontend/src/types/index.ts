/**
 * TrainingSetType — Type of workout session.
 * - DISTANCE: Workout defined by distance to cover (KM, M)
 * - DURATION: Workout defined by time duration (MIN, SEC)
 */
export type TrainingSetType = 'DISTANCE' | 'DURATION';

/**
 * TrainingSetUnit — Unit of measurement for training sets.
 * Compatible units depend on type:
 * - For DISTANCE: KM (kilometers), M (meters)
 * - For DURATION: MIN (minutes), SEC (seconds)
 */
export type TrainingSetUnit = 'KM' | 'M' | 'MIN' | 'SEC';

/**
 * DistanceBasedSet — Discriminated union type for distance-based training sets.
 * Guarantees that only KM or M units are used with DISTANCE type.
 */
export interface DistanceBasedSet {
  id?: number;
  type: 'DISTANCE';
  unit: 'KM' | 'M';        // Type-safe: only distance units allowed
  order: number;
  quantity: number;
  createdDate?: string;
}

/**
 * DurationBasedSet — Discriminated union type for duration-based training sets.
 * Guarantees that only MIN or SEC units are used with DURATION type.
 */
export interface DurationBasedSet {
  id?: number;
  type: 'DURATION';
  unit: 'MIN' | 'SEC';     // Type-safe: only duration units allowed
  order: number;
  quantity: number;
  createdDate?: string;
}

/**
 * TrainingSet — Represents a single training session or workout segment.
 * Discriminated union of DistanceBasedSet and DurationBasedSet for type safety.
 *
 * @property id - Unique identifier (auto-generated by backend)
 * @property type - Type of workout (DISTANCE or DURATION)
 * @property unit - Unit of measurement (must be compatible with type)
 * @property order - Sequence position within the training plan (1-based)
 * @property quantity - Numerical value of the exercise
 * @property createdDate - ISO date string when set was created
 */
export type TrainingSet = DistanceBasedSet | DurationBasedSet;

/**
 * Type guard to check if a training set is distance-based.
 * @param set - Training set to check
 * @returns true if set is distance-based, false otherwise
 */
export function isDistanceBased(set: TrainingSet): set is DistanceBasedSet {
  return set.type === 'DISTANCE';
}

/**
 * Type guard to check if a training set is duration-based.
 * @param set - Training set to check
 * @returns true if set is duration-based, false otherwise
 */
export function isDurationBased(set: TrainingSet): set is DurationBasedSet {
  return set.type === 'DURATION';
}

/**
 * TRAINING_SET_TYPE_LABELS — German UI labels for training set types.
 * Used in dropdowns and UI display.
 */
export const TRAINING_SET_TYPE_LABELS: Record<TrainingSetType, string> = {
  DISTANCE: 'Entfernung',
  DURATION: 'Dauer',
};

/**
 * TRAINING_SET_UNIT_LABELS — German UI labels for training set units.
 * Used in displays and form fields.
 */
export const TRAINING_SET_UNIT_LABELS: Record<TrainingSetUnit, string> = {
  KM: 'Kilometer',
  M: 'Meter',
  MIN: 'Minuten',
  SEC: 'Sekunden',
};

/**
 * Format a training set for display (e.g., "5 KM" or "30 MIN").
 * @param set - Training set to format
 * @returns formatted string with quantity and unit label
 */
export function formatTrainingSet(set: TrainingSet): string {
  return `${set.quantity} ${TRAINING_SET_UNIT_LABELS[set.unit]}`;
}
